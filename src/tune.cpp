// Capablanca - Texel tuner: fits evaluation weights to game results.
//
// Data: one position per line, "FEN;result" with result 1 / 0.5 / 0 from White's view.
// Output: src/tuned.inc (C++ initializers that init_eval() applies at startup).
#include "engine.h"
#include <atomic>
#include <chrono>
#include <cmath>
#include <fstream>
#include <iostream>
#include <thread>

namespace {

struct Sample {
    Position pos;
    float result;
};

std::vector<Sample> samples;
int nThreads = 8;

double sigmoid(double s, double K) { return 1.0 / (1.0 + std::pow(10.0, -K * s / 400.0)); }

double loss(double K) {
    std::vector<double> part(nThreads, 0.0);
    std::vector<std::thread> ts;
    size_t n = samples.size();
    for (int t = 0; t < nThreads; t++) {
        ts.emplace_back([&, t]() {
            double sum = 0;
            for (size_t i = t; i < n; i += nThreads) {
                const Sample& smp = samples[i];
                int e = evaluate(smp.pos);
                if (smp.pos.stm == BLACK) e = -e;
                double d = smp.result - sigmoid(e, K);
                sum += d * d;
            }
            part[t] = sum;
        });
    }
    for (auto& th : ts) th.join();
    double total = 0;
    for (double p : part) total += p;
    return total / double(n);
}

double fit_k() {
    double lo = 0.3, hi = 3.0;
    for (int it = 0; it < 30; it++) {
        double m1 = lo + (hi - lo) / 3, m2 = hi - (hi - lo) / 3;
        if (loss(m1) < loss(m2)) hi = m2; else lo = m1;
    }
    return (lo + hi) / 2;
}

// PST values as laid out in the "PST" tune param: [piece][square]{mg, eg}.
int* pst_base() {
    static auto params = tune_params();
    for (TuneParam& p : params)
        if (std::string(p.name) == "PST") return p.values;
    return nullptr;
}
int& pst(int pt, int sq, int eg) { return pst_base()[(pt * 64 + sq) * 2 + eg]; }

// Mean of one piece's PST half (mg or eg) over the squares the piece can stand on.
double pst_mean(int pt, int eg) {
    double sum = 0;
    int n = 0;
    for (int sq = (pt == PAWN ? 8 : 0); sq < (pt == PAWN ? 56 : 64); sq++, n++) sum += pst(pt, sq, eg);
    return sum / n;
}

// A uniform shift of a piece's PST acts like a change of its material value. Piece values are a
// style choice and frozen, so pull each table's mean back to where it started.
void recentre_pst(const double (&target)[6][2]) {
    for (int pt = PAWN; pt < KING; pt++)
        for (int eg = 0; eg < 2; eg++) {
            int shift = int(std::lround(pst_mean(pt, eg) - target[pt][eg]));
            if (!shift) continue;
            for (int sq = (pt == PAWN ? 8 : 0); sq < (pt == PAWN ? 56 : 64); sq++) pst(pt, sq, eg) -= shift;
        }
}

void write_params(const std::string& path) {
    std::ofstream out(path);
    out << "// Generated by the Texel tuner. Applied by init_eval().\n";
    for (const TuneParam& p : tune_params()) {
        out << "{\"" << p.name << "\", {";
        for (int i = 0; i < p.count; i++) out << (i ? "," : "") << p.values[i];
        out << "}},\n";
    }
}

} // namespace

void tune(const std::string& dataFile, int threads, int passes) {
    nThreads = std::max(1, threads);
    // Tune a symmetric evaluation: style multipliers are applied on top afterwards.
    StyleConfig saved = Style;
    Style.aggression = Style.defense = 100;
    UseNNUE = false; // the tuner fits the hand-written evaluation

    tt_resize(1); // the quiet filter clears the TT per sample; keep that cheap

    std::ifstream in(dataFile);
    std::string line;
    size_t read = 0;
    while (std::getline(in, line)) {
        size_t semi = line.rfind(';');
        if (semi == std::string::npos) continue;
        Sample s;
        s.pos.set_fen(line.substr(0, semi));
        s.result = std::stof(line.substr(semi + 1));
        read++;
        // Static eval is only meaningful in quiet positions: drop checks and positions
        // where captures still change the score.
        if (s.pos.in_check() || qsearch_score(s.pos) != evaluate(s.pos)) continue;
        samples.push_back(s);
    }
    std::cout << "read " << read << ", kept " << samples.size() << " quiet positions" << std::endl;
    if (samples.empty()) return;

    double K = fit_k();
    double best = loss(K);
    std::cout << "K = " << K << "  initial loss " << best << std::endl;

    double pstTarget[6][2];
    for (int pt = PAWN; pt < KING; pt++)
        for (int eg = 0; eg < 2; eg++) pstTarget[pt][eg] = pst_mean(pt, eg);

    auto params = tune_params();
    const int steps[] = {8, 4, 2, 1};
    for (int pass = 0; pass < passes; pass++) {
        int step = steps[std::min(pass, 3)];
        int improved = 0;
        auto t0 = std::chrono::steady_clock::now();
        for (TuneParam& p : params) {
            // Low piece values are a deliberate style choice, not something to fit to results.
            if (std::string(p.name) == "PieceValue") continue;
            for (int i = 0; i < p.count; i++) {
                int& v = p.values[i];
                int orig = v;
                bool better = false;
                for (int dir : {+1, -1}) {
                    v = orig + dir * step;
                    double l = loss(K);
                    if (l < best) { best = l; better = true; break; }
                }
                if (!better) v = orig;
                else improved++;
            }
        }
        recentre_pst(pstTarget);
        best = loss(K);
        double sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
        std::cout << "pass " << pass + 1 << " step " << step << "  loss " << best << "  improved " << improved
                  << "  (" << int(sec) << "s)" << std::endl;
        write_params("src/tuned.inc");
        if (!improved && step == 1) break;
    }
    Style = saved;
    std::cout << "done; wrote src/tuned.inc" << std::endl;
}
